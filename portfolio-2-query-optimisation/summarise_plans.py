#!/usr/bin/env python3
"""
Reads plans/before_*.txt and plans/after_*.txt (written by run_plans.ps1) and
produces performance-summary.md: one table of real measured numbers.
Nothing is estimated or typed by hand, so the table is only as good as your runs.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLANS = HERE / "plans"


def parse(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    exec_ms = re.search(r"Execution Time: ([\d.]+) ms", text)
    plan_ms = re.search(r"Planning Time: ([\d.]+) ms", text)
    lines = [l for l in text.splitlines() if "->" in l or re.match(r"^[A-Z][A-Za-z ]+(on|using)?", l)]
    nodes = re.findall(r"(Seq Scan on \w+|Index Only Scan(?: Backward)? using \w+|Index Scan(?: Backward)? using \w+|"
                       r"Bitmap Index Scan on \w+|Bitmap Heap Scan on \w+)", text)
    # keep order, drop duplicates
    seen, scans = set(), []
    for n in nodes:
        if n not in seen:
            seen.add(n)
            scans.append(n)
    hit = re.search(r"Buffers: shared hit=(\d+)(?: read=(\d+))?", text)
    shared = (int(hit.group(1)) + int(hit.group(2) or 0)) if hit else None
    return {
        "exec": float(exec_ms.group(1)) if exec_ms else None,
        "plan": float(plan_ms.group(1)) if plan_ms else None,
        "scans": scans,
        "buffers": shared,
    }


def fmt(v, suffix=""):
    return "n/a" if v is None else f"{v:,.2f}{suffix}" if isinstance(v, float) else f"{v:,}{suffix}"


def main():
    names = sorted({p.stem.split("_", 1)[1] for p in PLANS.glob("before_*.txt")})
    if not names:
        raise SystemExit("No plans found. Run run_plans.ps1 -Phase before / after first.")
    rows = ["| Query | Before ms | After ms | Speed up | Buffers before | Buffers after | Scan nodes before | Scan nodes after |",
            "|---|---:|---:|---:|---:|---:|---|---|"]
    for name in names:
        b = parse(PLANS / f"before_{name}.txt")
        a_path = PLANS / f"after_{name}.txt"
        a = parse(a_path) if a_path.exists() else {"exec": None, "buffers": None, "scans": []}
        speed = (f"{b['exec'] / a['exec']:.1f}x" if b["exec"] and a["exec"] else "n/a")
        rows.append(f"| {name} | {fmt(b['exec'])} | {fmt(a['exec'])} | {speed} | {fmt(b['buffers'])} | "
                    f"{fmt(a['buffers'])} | {'; '.join(b['scans']) or '-'} | {'; '.join(a['scans']) or '-'} |")
    out = HERE / "performance-summary.md"
    out.write_text("# Measured results (generated by summarise_plans.py)\n\n"
                   "Warm cache timings from EXPLAIN (ANALYZE, BUFFERS) on the machine that ran the plans.\n"
                   "Buffers are shared buffers touched (hit + read) by the plan's top node.\n\n"
                   + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {out}")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
